"""Choose the few-shot demos once, from the train split, with the global seed. Writes demos.json + prompt_review.md.

  python experiments/07-llm-offtheshelf-fewshot/select_demos.py                   # deterministic choice
  python experiments/07-llm-offtheshelf-fewshot/select_demos.py --pin ID ID ...   # replace the choice by these ids

Slots (prompt order A1 N1 A2 N2 A3 N3 A4, so answerable and unanswerable alternate and the share of unanswerable
demos, 3 of 7 = 43%, is close to train's 44%):
  answerable    siapa (1-5 word answer), kapan (1-5), berapa (1-5), apa (3-12 words, to show that a span can be a phrase)
  unanswerable  kapan, siapa, apa; each shares at least 2 content words with its passage, so it looks answerable,
                which is how this dataset's unanswerable questions are built
Every demo: passage 250-650 characters, a different passage per demo, question ending in "?" with no space before it
(" ?" is a dataset artifact, see eda/). Answerable demos: all gold answers agree, the answer occurs exactly once in
the passage (so the demo is unambiguous), and the gold span is clean: starts and ends with a word character (or a
closing bracket, %, ², °) and has balanced brackets and quotes.
Within a slot the candidates are sorted by id and one is drawn with random.Random(f"{GLOBAL_SEED}-demos-{slot}").
`--pin` keeps the same format (slot = question type) for hand-picked ids; review prompt_review.md afterwards.
"""
import sys as _sys, pathlib as _pl  # shared code: experiments/global/mrc
_sys.path.insert(0, str(_pl.Path(__file__).resolve().parents[1] / "global"))
from mrc.paths import ROOT, at_root  # noqa: E402
at_root()  # relative paths resolve from the project root
import argparse
import json
import random
import re

from fewshot import DEMOS, HERE, build_messages, demo_record, demos_hash, load_prompts
from mrc.eval_order import GLOBAL_SEED, load_order
from mrc.evaluate import load_jsonl
from mrc.paths import PROC

QTYPES = ["siapa", "kapan", "berapa", "dimana", "di mana", "mengapa", "bagaimana", "apa"]  # first match wins
STOP = set("yang dan di ke dari pada untuk dengan adalah itu ini apa siapa kapan dimana mana berapa bagaimana "
           "mengapa apakah dalam oleh atau sebagai juga tersebut nama".split())
SLOTS = [("A", "siapa", 1, 5), ("N", "kapan"), ("A", "kapan", 1, 5), ("N", "siapa"), ("A", "berapa", 1, 5),
         ("N", "apa"), ("A", "apa", 3, 12)]


def qtype(q: str) -> str:
    ql = q.lower()
    return next((t for t in QTYPES if re.search(rf"\b{t}\b", ql)), "other").replace("di mana", "dimana")


def words(s: str) -> set:
    return {w for w in re.findall(r"\w+", s.lower()) if w not in STOP and len(w) > 2}


def eligible(e: dict) -> bool:
    q = e["question"]
    if not (250 <= len(e["context"]) <= 650) or not re.search(r"\w\?$", q.strip()):  # no " ?" (an EDA artifact)
        return False
    if e["is_impossible"]:
        return len(words(e["question"]) & words(e["context"])) >= 2
    texts = {a["text"].strip() for a in e["answers"]}
    a = e["answers"][0]
    t = a["text"]
    clean = (re.match(r"^\w.*[\w)%²°]$|^\w$", t) and t.count("(") == t.count(")") and t.count('"') % 2 == 0)
    return (clean and len(texts) == 1 and e["context"].count(t) == 1
            and e["context"][a["answer_start"]:a["answer_start"] + len(a["text"])] == a["text"])


def choose(train: list[dict]) -> list[dict]:
    pool = sorted((e for e in train if eligible(e)), key=lambda e: e["id"])
    out, used_ctx = [], set()
    for slot in SLOTS:
        kind, qt = slot[0], slot[1]
        cands = [e for e in pool if e["is_impossible"] == (kind == "N") and qtype(e["question"]) == qt
                 and e["context"][:40] not in used_ctx]
        if kind == "A":
            cands = [e for e in cands if slot[2] <= len(e["answers"][0]["text"].split()) <= slot[3]]
        e = random.Random(f"{GLOBAL_SEED}-demos-{kind}{qt}").choice(cands)
        used_ctx.add(e["context"][:40])
        out.append(demo_record(e, f"{'answerable' if kind == 'A' else 'unanswerable'}-{qt}"))
    return out


def review(demos: list[dict], dev: dict) -> str:
    cfg = load_prompts()
    L = ["# Prompt and demos for review (07-llm-offtheshelf-fewshot)", "",
         "Generated by `select_demos.py`; edit `prompts.yaml` (instruction) or rerun `select_demos.py --pin ...` "
         "(demos), then regenerate this file. Nothing has been run on a model yet.", "",
         f"No-answer string: `{cfg['no_answer_string']}`. Demos: {len(demos)} from the train split, "
         f"seed {GLOBAL_SEED}, sha256 `{demos_hash(demos)[:16]}`.", "", "## Demos (in prompt order)", ""]
    for k, d in enumerate(demos, 1):
        L += [f"### {k}. {d['slot']} · `{d['id']}`", "", f"**Question:** {d['question']}", "",
              f"**Answer:** {'`' + d['answer'] + '`' if d['answer'] else '`unanswerable`'}"
              + (f" (char {d['answer_start']})" if d['answer'] else ""), "", f"> {d['context']}", ""]
    for v in cfg["variants"]:
        L += [f"## Variant `{v}`: system instruction", "", "```", cfg["variants"][v]["system"], "```", ""]
    first = dev[load_order("dev")[0]]
    msgs = build_messages(cfg, "fs_id", demos, first)
    L += ["## Full chat for the first dev question in the fixed order (variant `fs_id`)", "",
          f"{len(msgs)} messages: system, {len(demos)} demo pairs, the query. "
          f"About {sum(len(m['content']) for m in msgs)} characters.", ""]
    for m in msgs:
        L += [f"**{m['role']}**", "", "```", m["content"], "```", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pin", nargs="+", help="use these train ids, in this order, instead of the seeded choice")
    a = ap.parse_args()
    train = load_jsonl(PROC / "train.jsonl")
    if a.pin:
        by = {e["id"]: e for e in train}
        missing = [i for i in a.pin if i not in by]
        if missing:
            raise SystemExit(f"not in the train split: {missing}")
        demos = [demo_record(by[i], f"{'unanswerable' if by[i]['is_impossible'] else 'answerable'}-"
                                    f"{qtype(by[i]['question'])}") for i in a.pin]
        how = "pinned by hand: " + " ".join(a.pin)
    else:
        demos = choose(train)
        how = "select_demos.py slots " + " ".join("".join(map(str, s[:2])) for s in SLOTS)
    meta = {"seed": GLOBAL_SEED, "source": "data/processed/train.jsonl", "how": how,
            "sha256": demos_hash(demos), "demos": demos}
    DEMOS.write_text(json.dumps(meta, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    dev = {e["id"]: e for e in load_jsonl(PROC / "dev.jsonl")}
    (HERE / "prompt_review.md").write_text(review(demos, dev), encoding="utf-8", newline="\n")
    for d in demos:
        print(f"{d['slot']:22s} {d['id']}  {d['question']}  ->  {d['answer'] or 'unanswerable'}")
    print(f"wrote {DEMOS.relative_to(ROOT)} and prompt_review.md")


if __name__ == "__main__":
    main()
